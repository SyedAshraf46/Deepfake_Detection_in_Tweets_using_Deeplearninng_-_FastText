"""
Explanation generation for predictions
"""
from ml.preprocess import extract_keywords

def explain_prediction(tweet_text, prediction_result):
    """
    Generate human-readable explanation for prediction
    
    Args:
        tweet_text: Original tweet text
        prediction_result: Dict with prediction, confidence, keywords
    
    Returns:
        Explanation string
    """
    prediction = prediction_result.get('prediction', 'human')
    confidence = prediction_result.get('confidence', 0.5)
    keywords = prediction_result.get('keywords', [])
    
    confidence_percent = int(confidence * 100)
    
    if prediction == 'bot':
        explanation = f"This tweet is classified as **AI-generated/Bot** with {confidence_percent}% confidence. "
        
        if confidence_percent >= 80:
            explanation += "The model is highly confident this content was generated by an AI or automated system. "
        elif confidence_percent >= 60:
            explanation += "The model suggests this content likely came from an automated source. "
        else:
            explanation += "The model indicates this content may be AI-generated, but with moderate confidence. "
        
        if keywords:
            explanation += f"Key indicators include: {', '.join(keywords[:3])}. "
        
        explanation += "Common bot characteristics detected include repetitive patterns, unusual word choices, or structural anomalies typical of language models."
    else:
        explanation = f"This tweet is classified as **Human-written** with {confidence_percent}% confidence. "
        
        if confidence_percent >= 80:
            explanation += "The model is highly confident this content was written by a human. "
        elif confidence_percent >= 60:
            explanation += "The model suggests this content likely came from a human author. "
        else:
            explanation += "The model indicates this content appears human-written, but with moderate confidence. "
        
        if keywords:
            explanation += f"Natural language patterns detected include: {', '.join(keywords[:3])}. "
        
        explanation += "The text shows characteristics typical of human communication, such as natural variation, authentic expression, and contextual understanding."
    
    return explanation

def get_detailed_explanation(tweet_text, prediction_result):
    """
    Get more detailed explanation with technical details
    """
    base_explanation = explain_prediction(tweet_text, prediction_result)
    
    prediction = prediction_result.get('prediction', 'human')
    confidence = prediction_result.get('confidence', 0.5)
    
    technical_details = f"\n\n**Technical Details:**\n"
    technical_details += f"- Prediction: {prediction.upper()}\n"
    technical_details += f"- Confidence Score: {confidence:.3f}\n"
    technical_details += f"- Model: Bi-LSTM with FastText Embeddings\n"
    
    if prediction == 'bot':
        technical_details += f"- Risk Level: {'High' if confidence > 0.8 else 'Medium' if confidence > 0.6 else 'Low'}\n"
    else:
        technical_details += f"- Authenticity Level: {'High' if confidence > 0.8 else 'Medium' if confidence > 0.6 else 'Low'}\n"
    
    return base_explanation + technical_details

